#!/usr/bin/env python3
from __future__ import annotations

import json
import os
import re
import urllib.request
from pathlib import Path
from typing import Any


ORG = "ai-workspace-services"
OUTPUT = Path(__file__).resolve().parents[1] / "profile" / "README.md"

PACKAGE_MAP = {
    "accounts": {"title": "accounts", "description": "账户与身份相关镜像。"},
    "billing-service": {"title": "billing-service", "description": "计费服务镜像。"},
    "docs": {"title": "docs", "description": "文档站镜像。"},
    "console": {"title": "console", "description": "控制台前端镜像。"},
    "postgresql": {"title": "postgresql", "description": "PostgreSQL 基础镜像。"},
}

ENV_PACKAGE_GROUPS = {
    "sit": ["console"],
    "uat": ["accounts", "billing-service", "docs", "postgresql"],
    "prod": [],
}

ENV_PRIORITY = {
    "sit": [re.compile(r"^sit-"), re.compile(r"^snapshot-")],
    "uat": [re.compile(r"^uat-"), re.compile(r"^uat/")],
    "prod": [re.compile(r"^prod-"), re.compile(r"^prod/"), re.compile(r"^v\d")],
}


def api(path: str) -> Any:
    req = urllib.request.Request(
        f"https://api.github.com{path}",
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "ai-workspace-services-homepage-generator",
        },
    )
    with urllib.request.urlopen(req) as resp:
        return json.load(resp)


def list_packages() -> list[dict[str, Any]]:
    return api(f"/orgs/{ORG}/packages?package_type=container&per_page=100")


def list_versions(package_name: str) -> list[dict[str, Any]]:
    return api(f"/orgs/{ORG}/packages/container/{package_name}/versions?per_page=20")


def newest_version_for_env(versions: list[dict[str, Any]], env: str) -> dict[str, Any] | None:
    patterns = ENV_PRIORITY[env]
    scored = []
    for version in versions:
        tags = version.get("metadata", {}).get("container", {}).get("tags", []) or []
        score = 0
        for tag in tags:
            if any(p.match(tag) for p in patterns):
                score += 10
            elif tag == "latest" and env in {"sit", "uat"}:
                score += 1
        if score > 0:
            scored.append((score, version))
    if scored:
        scored.sort(key=lambda item: (item[0], item[1].get("created_at", "")), reverse=True)
        return scored[0][1]
    return versions[0] if versions else None


def classify_env(version: dict[str, Any]) -> str | None:
    tags = version.get("metadata", {}).get("container", {}).get("tags", []) or []
    for env, patterns in ENV_PRIORITY.items():
        for tag in tags:
            if any(pattern.match(tag) for pattern in patterns):
                return env
    if "latest" in tags:
        return "uat"
    if any(tag.startswith("sha-") for tag in tags):
        return "sit"
    return None


def env_version_for_package(package_name: str, env: str) -> dict[str, Any] | None:
    versions = list_versions(package_name)
    matched = []
    for version in versions:
        if classify_env(version) == env:
            matched.append(version)
    if matched:
        matched.sort(key=lambda version: version.get("created_at", ""), reverse=True)
        return matched[0]
    if env == "sit" and package_name in ENV_PACKAGE_GROUPS["sit"]:
        return newest_version_for_env(versions, "sit")
    if env == "uat" and package_name in ENV_PACKAGE_GROUPS["uat"]:
        return newest_version_for_env(versions, "uat")
    if env == "prod" and package_name in ENV_PACKAGE_GROUPS["prod"]:
        return newest_version_for_env(versions, "prod")
    return None


def short_tag(tag: str) -> str:
    if tag.startswith("sha-"):
        return tag[4:11]
    if len(tag) > 40:
        return tag[:20] + "…" + tag[-19:]
    return tag


def format_tags(version: dict[str, Any] | None) -> str:
    """At most 2 tags; drop sha- tags when a human-readable tag exists."""
    if not version:
        return "—"
    tags = version.get("metadata", {}).get("container", {}).get("tags", []) or []
    named = [t for t in tags if not t.startswith("sha-") and t != "latest"]
    picked = named[:1] or [t for t in tags if t.startswith("sha-")][:1]
    if "latest" in tags:
        picked.append("latest")
    return " · ".join(f"`{short_tag(t)}`" for t in picked[:2]) if picked else "—"


def updated_at(version: dict[str, Any] | None) -> str:
    if not version or not version.get("created_at"):
        return "—"
    return version["created_at"].replace("T", " ")[:16]


TEXT = {
    "en": {
        "comment": "generated by CI, do not edit by hand",
        "header": "| Env | Purpose | Status | Latest | Updated (UTC) |",
        "purpose": {"prod": "Production", "uat": "Pre-release", "sit": "Integration"},
        "none": "no_release",
        "summary": "Image tags",
        "img_header": "| Env | Image | Tag |",
    },
    "zh": {
        "comment": "CI 生成，请勿手改",
        "header": "| 环境 | 定位 | 状态 | 最新版本 | 更新时间 (UTC) |",
        "purpose": {"prod": "生产发布", "uat": "预发验证", "sit": "验证集成"},
        "none": "暂无发布",
        "summary": "镜像清单 (Image Tags)",
        "img_header": "| 环境 | 镜像 | Tag |",
    },
}

ENV_LEAD_PACKAGE = {"prod": "postgresql", "uat": "billing-service", "sit": "console"}

TARGETS = {
    "en": OUTPUT,
    "zh": OUTPUT.with_name("README_ZH.md"),
}

BLOCK = re.compile(r"<!-- RELEASES:START.*?<!-- RELEASES:END -->", re.S)


def status_badge(version: dict[str, Any] | None, lang: str) -> str:
    if version:
        return "![artifact found](https://img.shields.io/badge/-artifact_found-2F855A)"
    return f"![none](https://img.shields.io/badge/-{TEXT[lang]['none']}-lightgrey)"


def collect() -> dict[str, Any]:
    latest = {env: env_version_for_package(ENV_LEAD_PACKAGE[env], env) for env in ("prod", "uat", "sit")}
    images = []
    for env in ("sit", "uat", "prod"):
        for package_name in ENV_PACKAGE_GROUPS[env]:
            images.append((env, PACKAGE_MAP[package_name]["title"], env_version_for_package(package_name, env)))
    return {"latest": latest, "images": images}


def render_block(data: dict[str, Any], lang: str) -> str:
    t = TEXT[lang]
    lines = [f"<!-- RELEASES:START — {t['comment']} -->", t["header"], "| :--- | :--- | :--- | :--- | :--- |"]
    for env in ("prod", "uat", "sit"):
        version = data["latest"][env]
        lines.append(
            f"| `{env}` | {t['purpose'][env]} | {status_badge(version, lang)} | {format_tags(version)} | {updated_at(version)} |"
        )
    lines += ["", "<details>", f"<summary>{t['summary']}</summary>", "", t["img_header"], "| :--- | :--- | :--- |"]
    for env, title, version in data["images"]:
        lines.append(f"| {env} | {title} | {format_tags(version)} |")
    lines += ["", "</details>", "<!-- RELEASES:END -->"]
    return "\n".join(lines)


def main() -> int:
    if not os.environ.get("GITHUB_TOKEN"):
        raise SystemExit("GITHUB_TOKEN is required")
    data = collect()
    for lang, path in TARGETS.items():
        text = path.read_text(encoding="utf-8")
        if not BLOCK.search(text):
            raise SystemExit(f"RELEASES markers missing in {path}")
        path.write_text(BLOCK.sub(lambda _: render_block(data, lang), text), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
